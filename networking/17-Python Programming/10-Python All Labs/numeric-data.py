print("Python has three numeric types: in, float, and complex")

#Creating a variable
myValue = 1 

#Printing the value assigned to the variable myValue
print(myValue)

#Printing the data type of the variable myValue
print(type(myValue))

#Concatenating String using the built-in function str
print(str(myValue) + "is of the data type" + str(type(myValue)))

#Exercise 4: Introducing the complex data type
myValue = 5j
print(myValue)
print(type(myValue))

#Combining text using the built-in function str()
print(str(myValue) + " is of the data type" + str(type(myValue)))

#Exercise 5: Introducing the bool data type 
myValue = True 
print(myValue)
print(type(myValue))
print(str(myValue) + " is of the data type " + str(type(myValue)))

